DB_PATH = os.path.join(os.path.dirname(__file__), '..', 'data', 'memory_claude.db')


def create_table(cur):
    """is_forecast 컬럼이 포함된 earnings_reports 테이블 생성"""
    cur.execute("""
    CREATE TABLE IF NOT EXISTS earnings_reports (
        id                  INTEGER PRIMARY KEY AUTOINCREMENT,
        entity_id           TEXT NOT NULL REFERENCES entities(entity_id),
        period              TEXT NOT NULL,
        report_date         TEXT,

        revenue             REAL NOT NULL,
        op_income           REAL,
        net_income          REAL,
        unit                TEXT DEFAULT 'B_USD',

        eps_actual          REAL,
        eps_consensus       REAL,
        consensus_revenue   REAL,
        beat_miss_status    TEXT,

        gross_margin_pct    REAL,
        op_margin_pct       REAL,
        capex               REAL,

        revenue_breakdown   TEXT,
        guidance_next_q     TEXT,

        key_takeaways       TEXT,
        source              TEXT,

        is_forecast         INTEGER DEFAULT 0,

        created_at          TEXT DEFAULT (datetime('now'))
    )
    """)
    cur.execute("CREATE INDEX IF NOT EXISTS idx_er_entity ON earnings_reports(entity_id)")
    cur.execute("CREATE INDEX IF NOT EXISTS idx_er_period ON earnings_reports(period)")
    cur.execute("CREATE INDEX IF NOT EXISTS idx_er_date ON earnings_reports(report_date)")
    cur.execute("CREATE INDEX IF NOT EXISTS idx_er_forecast ON earnings_reports(is_forecast)")

    cur.execute("DROP VIEW IF EXISTS v_earnings_summary")
    cur.execute("""
    CREATE VIEW v_earnings_summary AS
    SELECT
        e.name_ko                           AS 기업,
        r.period                            AS 분기,
        r.report_date                       AS 발표일,
        r.revenue || ' ' || r.unit          AS 매출,
        r.op_income || ' ' || r.unit        AS 영업익,
        CASE
            WHEN r.consensus_revenue IS NOT NULL
            THEN ROUND(r.revenue - r.consensus_revenue, 2) || ' ' || r.unit
            ELSE '-'
        END                                 AS 매출서프라이즈,
        COALESCE('$' || r.eps_actual, '-')  AS 실제EPS,
        COALESCE('$' || r.eps_consensus,'-') AS 예상EPS,
        COALESCE(r.gross_margin_pct||'%','-') AS 매출총이익률,
        COALESCE(r.beat_miss_status, '-')   AS 실적판정,
        CASE WHEN r.is_forecast = 1 THEN '전망' ELSE '확정' END AS 데이터구분,
        r.revenue_breakdown                 AS 매출비중,
        r.guidance_next_q                   AS 차기가이던스
    FROM earnings_reports r
    JOIN entities e ON r.entity_id = e.entity_id
    ORDER BY r.period DESC, e.layer, e.entity_id
    """)


def insert_row(cur, entity_id, period, report_date, rev, op, net, unit,
               eps_a, eps_c, con_rev, status, gm, breakdown, takeaways,
               source, is_forecast):
    cur.execute("""
        INSERT INTO earnings_reports (
            entity_id, period, report_date,
            revenue, op_income, net_income, unit,
            eps_actual, eps_consensus, consensus_revenue, beat_miss_status,
            gross_margin_pct, revenue_breakdown, key_takeaways, source,
            is_forecast
        ) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)
    """, (entity_id, period, report_date,
          rev, op, net, unit,
          eps_a, eps_c, con_rev, status,
          gm, breakdown, takeaways, source,
          is_forecast))


